				FROM USUARIOS U
				INNER JOIN DATOS_PERSONALES P ON U.IDX_DATOS_PERSONALES= P.DATOS_PERSONALES_ID
				INNER JOIN USUARIOS_TIPO UT ON U.IDX_USUARIO_TIPO = UT.USUARIO_TIPO_ID
			END

		  IF @filter = 'FOTO'
			BEGIN
				UPDATE DATOS_PERSONALES
				SET FOTO = @foto
				WHERE DATOS_PERSONALES_ID = @personaldataid
			END

END
