CREATE OR ALTER PROCEDURE [dbo].[SP_CARGAINICIAL_DASHBOARD] 

AS
BEGIN
	--VENTA POR MES
	declare @anio INT = YEAR(GETDATE());
WITH Meses AS (
    SELECT 1 AS MES, 'Ene' AS MES_NOMBRE
    UNION SELECT 2, 'Feb'
    UNION SELECT 3, 'Mar'
    UNION SELECT 4, 'Abr'
    UNION SELECT 5, 'May'
    UNION SELECT 6, 'Jun'
    UNION SELECT 7, 'Jul'
    UNION SELECT 8, 'Ago'
    UNION SELECT 9, 'Sep'
    UNION SELECT 10, 'Oct'
    UNION SELECT 11, 'Nov'
    UNION SELECT 12, 'Dic'
)
SELECT 
    SUM(f.COSTO_TOTAL) AS TOTAL, 
    m.MES, 
    m.MES_NOMBRE, 
    YEAR(f.FECHA_VENTA) AS ANIO
FROM Meses m
LEFT JOIN FACTURAS f ON MONTH(f.FECHA_VENTA) = m.MES AND YEAR(f.FECHA_VENTA) = @anio
GROUP BY m.MES, m.MES_NOMBRE, YEAR(f.FECHA_VENTA)
ORDER BY m.MES;

--VENTA POR DIA
SELECT SUM(COSTO_TOTAL) AS TOTAL, CONVERT(DATE,FECHA_VENTA) AS FECHA FROM FACTURAS
WHERE CONVERT(DATE, FECHA_VENTA) = CONVERT(DATE, GETDATE()) 
GROUP BY CONVERT(DATE, FECHA_VENTA)

--CITAS PARA HOY
SELECT COUNT(APPT_ID) AS CITAS_HOY FROM CITAS
WHERE CONVERT(DATE, FECHA_CITA) = CONVERT(DATE, GETDATE())

--CITAS PARA HOY ATENDIDAS
SELECT COUNT(APPT_ID) AS CITAS_ATENDIDAS_HOY FROM CITAS
INNER JOIN CITAS_ESTADOS ON CITAS.IDX_ESTADOS = CITAS_ESTADOS.ESTADOS_ID
WHERE CONVERT(DATE, FECHA_CITA) = CONVERT(DATE, GETDATE()) AND CITAS_ESTADOS.CITAS_ESTADOS = 'ASISTIDO'

--FACTURAS POR DÍA
SELECT COUNT(ID_FACTURA) AS TOTAL_FACTUTAS FROM FACTURAS
WHERE CONVERT(DATE, FECHA_VENTA) = CONVERT(DATE, GETDATE())

SELECT CLIENTE_ID, NOMBRES, APELLIDOS FROM CLIENTES 

SELECT SERVICIO_ID, SERVICIO, COSTO_REGULAR FROM SERVICIOS WHERE ESTADOS = 1

SELECT 
CI.APPT_ID, CI.IDX_CLIENTE, CI.IDX_ESTADOS, CI.IDX_SERVICIO, CI.IDX_USUARIO_CREADOR, CI.FECHA_CITA,
(CL.NOMBRES + CL.APELLIDOS) AS CLIENTE, CL.NUMERO_TELEFONO,
DP.NOMBRES,
SE.SERVICIO,
CIE.CITAS_ESTADOS,
CONVERT(varchar(15),  CAST(CI.FECHA_CITA AS TIME), 100) as hora 
FROM CITAS CI
INNER JOIN CLIENTES CL ON CI.IDX_CLIENTE = CL.CLIENTE_ID
INNER JOIN USUARIOS US ON CI.IDX_USUARIO_CREADOR = US.USUARIO_ID
INNER JOIN DATOS_PERSONALES DP ON US.IDX_DATOS_PERSONALES = DP.DATOS_PERSONALES_ID
INNER JOIN SERVICIOS SE ON CI.IDX_SERVICIO = SE.SERVICIO_ID
INNER JOIN CITAS_ESTADOS CIE ON CI.IDX_ESTADOS = CIE.ESTADOS_ID
--WHERE CONVERT(DATE, CI.FECHA_CITA) >= CONVERT(DATE, GETDATE())
ORDER BY FECHA_CITA DESC;

	--GASTOS POR MES
WITH Meses AS (
      SELECT 1 AS MES, 'Ene' AS MES_NOMBRE
    UNION SELECT 2, 'Feb'
    UNION SELECT 3, 'Mar'
    UNION SELECT 4, 'Abr'
    UNION SELECT 5, 'May'
    UNION SELECT 6, 'Jun'
    UNION SELECT 7, 'Jul'
    UNION SELECT 8, 'Ago'
    UNION SELECT 9, 'Sep'
    UNION SELECT 10, 'Oct'
    UNION SELECT 11, 'Nov'
    UNION SELECT 12, 'Dic'
)
SELECT 
    SUM(f.COSTO_TOTAL) AS TOTAL, 
    m.MES, 
    m.MES_NOMBRE, 
    YEAR(f.FECHA_COMPRA) AS ANIO
FROM Meses m
LEFT JOIN COMPRAS f ON MONTH(f.FECHA_COMPRA) = m.MES AND YEAR(f.FECHA_COMPRA) = @anio
GROUP BY m.MES, m.MES_NOMBRE, YEAR(f.FECHA_COMPRA)
ORDER BY m.MES;

END
