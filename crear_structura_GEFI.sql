-- Description:	<Description, Carga facturas por fecha>
-- =============================================
CREATE OR ALTER PROCEDURE [dbo].[SP_CARGADO_FACTURAS]
	-- Add the parameters for the stored procedure here
	@todas bit,
	@fechaInicial datetime = null,
	@fechaFinal datetime = null,
	@cliente decimal,
	@usuario decimal
AS
BEGIN
	SET NOCOUNT ON;

    -- Insert statements for procedure here
	
	SELECT FC.ID_FACTURA, FC.COSTO_TOTAL, FC.IDX_CLIENTE, FC.IDX_USUARIO, FORMAT(FC.FECHA_VENTA, 'dd/MM/yyyy hh:mm tt') as FECHA_VENTA, 
	CONCAT(CL.NOMBRES, ' ', CL.APELLIDOS) AS CLIENTE_NOMBRE, CL.NUMERO_TELEFONO AS TELEFONO_CLIENTE,
	CONCAT(DP.NOMBRES, ' ', DP.APELLIDOS) AS USUARIO_NOMBRE, DP.NUMERO_TELEFONO AS TELEFONO_USUARIO

	INTO #CLIENTES

	FROM FACTURAS FC
	INNER JOIN CLIENTES CL ON FC.IDX_CLIENTE = CL.CLIENTE_ID
	INNER JOIN USUARIOS US ON FC.IDX_USUARIO = US.USUARIO_ID
	INNER JOIN DATOS_PERSONALES DP ON US.IDX_DATOS_PERSONALES = DP.DATOS_PERSONALES_ID

	WHERE ((FC.FECHA_VENTA >= isnull(@fechaInicial,FC.FECHA_VENTA) AND FC.FECHA_VENTA <= isnull(@fechaFinal,FC.FECHA_VENTA)) OR @todas = 1)
	AND (FC.IDX_USUARIO = @usuario OR @usuario = 0)
	AND (FC.IDX_CLIENTE = @cliente OR @cliente = 0)

	--Mostrar todas las facturas
	SELECT * FROM #CLIENTES

