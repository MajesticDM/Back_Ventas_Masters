CREATE OR ALTER PROCEDURE [dbo].[SP_INSERT_UPDATE_USERS]
	-- Add the parameters for the stored procedure here
		@filter				varchar(50),
		@personaldataid		numeric(18,0) = null,
		@userid				numeric(18,0) = null,
		@username			varchar(100)  = null,
		@userlastname		varchar(100)  = null,
		@userphonenumber	 numeric(18,0)  = null,
		@useremail			varchar(100)  = null,
		@datastatus			bit = null,
		@usernametologin	 varchar(50)  = null,
		@userpassword		varchar(max)  = null,
		@userstatus			bit   = null,
		@usertype			numeric(18,0) = null,
		@foto				varchar(max) = null
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

		IF @filter = 'DATAINSERT'
		BEGIN
		--INSERTS
		--SELECT * FROM DATOS_PERSONALES

		INSERT INTO DATOS_PERSONALES(NOMBRES,APELLIDOS,NUMERO_TELEFONO,EMAIL,ESTADOS)
		VALUES (@username,@userlastname,@userphonenumber,@useremail,1)

		DECLARE @lastpersonaldata numeric(18,0) = (SELECT SCOPE_IDENTITY()) -- To get the last id to create an user with this data

		INSERT  INTO USUARIOS(IDX_USUARIO_TIPO,IDX_DATOS_PERSONALES,USUARIO,CONTRASEÑA,ESTADOS)
		VALUES (@usertype,@lastpersonaldata,@usernametologin,@userpassword,1)

		SELECT @lastpersonaldata;
		END

		IF @filter = 'DATAUPDATE'
			BEGIN
		       --UPDATES
		       UPDATE DATOS_PERSONALES SET
		       NOMBRES = @username,
		       APELLIDOS = @userlastname,
		       NUMERO_TELEFONO = @userphonenumber,
		       EMAIL = @useremail
			   --FOTO = @foto
		       WHERE DATOS_PERSONALES_ID = @personaldataid
		       
		       UPDATE USUARIOS SET
		       IDX_USUARIO_TIPO = @usertype,
		       USUARIO = @usernametologin,
		       CONTRASEÑA = @userpassword,
		       ESTADOS = @userstatus
		       WHERE USUARIO_ID = @userid

		  END

		  IF @filter = 'DISPLAY'
			BEGIN
				SELECT U.USUARIO_ID, P.DATOS_PERSONALES_ID, UT.USUARIO_TIPO_ID,CONCAT(P.NOMBRES,' ', P.APELLIDOS) AS Nombre, P.NUMERO_TELEFONO  [NumeroTelefono], P.EMAIL AS [Email],
