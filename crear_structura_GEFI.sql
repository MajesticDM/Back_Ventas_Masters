CREATE OR ALTER PROCEDURE SP_MODIFICACION_NOTIFICACIONES_CONFIGURACION

@accion varchar(100),
@id_notificacion numeric(18,0),
@servicio numeric(18,0),
@periocidad numeric(18,0),
@periocidad_inmediata bit,
@solo_activos bit,
@tipo_notificacion varchar(100)

AS
BEGIN

	IF(@accion = 'guardar')
		BEGIN
			IF((SELECT COUNT(*) FROM CONFIGURACION_NOTIFICACIONES WHERE IDX_SERVICIO = @servicio AND IDX_PERIOCIDAD = @periocidad AND TIPO_NOTIFICACION = @tipo_notificacion) = 0 )
				BEGIN
					INSERT INTO CONFIGURACION_NOTIFICACIONES (IDX_SERVICIO, IDX_PERIOCIDAD, BIT_PERIOCIDAD_INMEDIATA, BIT_SOLO_ACTIVOS, TIPO_NOTIFICACION) VALUES
					(@servicio,@periocidad,@periocidad_inmediata,@solo_activos,@tipo_notificacion)

					SELECT 'La configuracion de la notificación de '+ @tipo_notificacion +' fue guardada.' AS RESULTADO
				END
			ELSE
				BEGIN
					SELECT 'La configuración que tratas de agregar ya existe, valida nuevamente.' as RESULTADO
				END
		END
	ELSE IF(@accion = 'eliminar')
		BEGIN
			DELETE FROM CONFIGURACION_NOTIFICACIONES WHERE ID_CONFIG_NOTIFICACION = @id_notificacion

			SELECT 'La configuración de '+ @tipo_notificacion +' fue eliminada con éxito' as RESULTADO

		END

END
