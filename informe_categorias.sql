CREATE OR ALTER PROCEDURE SP_CARGAR_CATEGORIAS

AS
BEGIN

SELECT 
    c.CATEGORIA_ID,
    c.CATEGORIA,
    c.ESTADOS,
    CAST(
        COALESCE(SUM(p.COSTO_X_UNIDAD * p.GRAMAJE_DEL_PRODUCTO) / NULLIF(SUM(p.GRAMAJE_DEL_PRODUCTO), 0), 0)
    AS DECIMAL(18, 2)) AS ponderado,
    SUM(GRAMAJE_DEL_PRODUCTO) as gramos
    
FROM CATEGORIAS c
LEFT JOIN PRODUCTOS p ON p.IDX_CATEGORIA = c.CATEGORIA_ID
GROUP BY c.CATEGORIA_ID, c.CATEGORIA, c.ESTADOS;


END